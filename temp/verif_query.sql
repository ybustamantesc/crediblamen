SELECT a.code, a.name, a.naturaleza,
ROUND(COALESCE(SUM(e.debit - e.credit),0),2) AS raw,
CASE WHEN a.naturaleza='deudora' THEN ROUND(COALESCE(SUM(e.debit - e.credit),0),2)
     WHEN a.naturaleza='acreedora' THEN ROUND(-COALESCE(SUM(e.debit - e.credit),0),2)
     ELSE ROUND(COALESCE(SUM(e.debit - e.credit),0),2) END AS display
FROM tb_account a
LEFT JOIN tb_journal_entry e ON e.account_id = a.id
LEFT JOIN tb_journal j ON j.id = e.journal_id AND j.posted = 1 AND (j.voided IS NULL OR j.voided = 0)
WHERE a.code IN ('14040101101','26010401201','26040301201','26040301203','26050101201','26050101202','26050301101','26050301201','27010201201','27010201202','27010201203','27010401101','27010701201','27010701202','27010901201','29290103201','32010301201','39010101201','41060101201','41060101202','41060101203','41090101201','42030101201','43020501201','43430301101','45010101201','45450101101','54030101201','54050701301','54059901203','55010101201','55550101101','63010101201','9999')
GROUP BY a.id
ORDER BY a.code;
